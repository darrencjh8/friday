"""onedrive-login.py walks Microsoft's login screens with Bitwarden secrets and no LLM.

The walk is tested against a fake page that replays the steps STEP_JS reports,
so these cover the decisions: what gets typed where, when to give up, and that
neither secret ever reaches an error message.
"""

from __future__ import annotations

import importlib.util
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "hermes" / "scripts" / "onedrive-login.py"
spec = importlib.util.spec_from_file_location("onedrive_login", SCRIPT)
od = importlib.util.module_from_spec(spec)
spec.loader.exec_module(od)

EMAIL, PASSWORD = "friday@example.com", "hunter2"
SECRET = "GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ"  # RFC 6238 test key
CODE_URL = "https://login.microsoftonline.com/common/oauth2/nativeclient?code=abc"


class FakePage:
    """Replays one step per STEP_JS call; the redirect arrives once steps run out."""

    def __init__(self, steps):
        self.steps = list(steps)
        self.typed = []
        self.code_url = None

    def navigate(self, url):
        self.url = url

    def evaluate(self, js):
        if js is not od.STEP_JS:
            return None
        if not self.steps:
            self.code_url = CODE_URL
            return {"kind": "wait"}
        return self.steps.pop(0)

    def type(self, text):
        self.typed.append(text)

    def location(self):
        return "'Somewhere' at login.live.com/x"


def walk(steps, totp_secret=None):
    page = FakePage(steps)
    return od.login(page, "https://auth", EMAIL, PASSWORD, totp_secret, timeout=5, pause=0), page


class LoginWalkTest(unittest.TestCase):
    def test_types_email_then_password_and_returns_the_redirect(self) -> None:
        url, page = walk([{"kind": "email"}, {"kind": "wait"}, {"kind": "password"},
                          {"kind": "clicked", "text": "Yes"}])
        self.assertEqual(url, CODE_URL)
        self.assertEqual(page.typed, [EMAIL, PASSWORD])

    def test_authenticator_step_types_the_current_totp(self) -> None:
        _, page = walk([{"kind": "email"}, {"kind": "password"},
                        {"kind": "code", "text": "Enter the code generated by your authenticator app"}],
                       totp_secret=SECRET)
        self.assertRegex(page.typed[2], r"^\d{6}$")

    def test_code_it_cannot_provide_stops_the_walk(self) -> None:
        with self.assertRaisesRegex(od.LoginError, "cannot provide"):
            walk([{"kind": "password"}, {"kind": "code", "text": "Enter the code we emailed you"}], SECRET)
        with self.assertRaisesRegex(od.LoginError, "cannot provide"):
            walk([{"kind": "code", "text": "Enter the code generated by your authenticator app"}])

    def test_password_is_never_typed_twice(self) -> None:
        with self.assertRaisesRegex(od.LoginError, "password again"):
            walk([{"kind": "password"}, {"kind": "password"}])

    def test_error_text_hides_the_email(self) -> None:
        with self.assertRaises(od.LoginError) as caught:
            walk([{"kind": "error", "text": f"No account found for {EMAIL}"}])
        self.assertNotIn(EMAIL, str(caught.exception))

    def test_endless_prompts_give_up(self) -> None:
        with self.assertRaisesRegex(od.LoginError, "too many prompts"):
            walk([{"kind": "clicked", "text": "Next"}] * 10)


class TotpTest(unittest.TestCase):
    def test_rfc6238_vectors(self) -> None:
        self.assertEqual(od.totp(SECRET, 59), "287082")
        self.assertEqual(od.totp(SECRET, 1111111109), "081804")
        self.assertEqual(od.totp(SECRET.lower()[:16] + " " + SECRET.lower()[16:], 59), "287082")


if __name__ == "__main__":
    unittest.main()
